const makeHistory = (base, wave = 1) =>
  Array.from({ length: 34 }, (_, index) => {
    const angle = index / 3.2;
    const drift = (index - 16) * base * 0.0009;
    const swing = Math.sin(angle * wave) * base * 0.012;
    const pulse = Math.cos(angle * 0.7) * base * 0.006;

    return {
      label: `${String(9 + Math.floor(index / 4)).padStart(2, '0')}:${index % 4 === 0 ? '15' : String((index % 4) * 15).padStart(2, '0')}`,
      price: Number((base + drift + swing + pulse).toFixed(2)),
    };
  });

